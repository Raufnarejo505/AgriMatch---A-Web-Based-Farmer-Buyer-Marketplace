export function translateInterface(source: string, language: "en" | "ur"): string {
  if (language === "en") return source;
  const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return source;
  const [, before, label, after] = match;
  const direct = urduTranslations[label];
  if (direct) return before + direct + after;
  const page = label.match(/^Page (\d+) of (\d+) · (\d+) results?$/);
  if (page) return before + `صفحہ ${page[1]} از ${page[2]} · ${page[3]} نتائج` + after;
  return source;
}
